namespace StrategyGame.ConsoleGame;

// Структура Coordinate представляет простую пару чисел (X, Y).
// В данном случае использование *структуры* оправдано, потому что:
// 1. Coordinate — это небольшой, неизменяемый тип данных-значение (value type).
// 2. Экземпляры таких типов логически представляют "значения", а не "объекты с поведением".
// 3. Структуры хранятся в стеке (или inline внутри других объектов), что снижает нагрузку на сборщик мусора.
// 4. Для координат не нужно семантики ссылочного равенства — важно именно равенство значений.
// 5. Структуры особенно полезны для математических и геометрических вычислений, где требуется высокая производительность без лишних аллокаций.

// Ключевое слово readonly делает структуру *неизменяемой* (immutable):
// - Все поля должны быть readonly.
// - Методы не могут изменять состояние экземпляра.
// - Компилятор не создаёт защитные копии при передаче структуры, что повышает производительность.
// - Такая структура ведёт себя как значение, которое нельзя случайно изменить.

public readonly struct Coordinate
{
    public Coordinate(int x, int y)
    {
        X = x;
        Y = y;
    }

    public readonly int X;
    public readonly int Y;
}

// Аналогичное поведение можно достичь с помощью record, который является ссылочным типом,
// но предоставляет удобную поддержку для неизменяемости и структурного равенства.
// Ниже — эквивалентная запись через record (с другим именем):

public record CoordinateRecord(int X, int Y);

// Отличия:
// - record — ссылочный тип, хранится в куче.
// - readonly struct — тип-значение, хранится в стеке.
// - Оба неизменяемы и поддерживают сравнение по значению, но record имеет больше накладных расходов.
// - Для небольших математических типов предпочтительнее readonly struct, для моделей данных — record.

// Почему для математических типов (например, точек, векторов, координат) лучше использовать readonly struct,
// а не record, хотя оба умеют сравниваться "по значению":

// 1. record — это ссылочный тип (class). Он живёт в куче, и при каждом создании такого объекта
//    происходит выделение памяти под ссылку. При работе с большим количеством объектов (например,
//    миллионы точек в расчётах) это создаёт нагрузку на сборщик мусора и замедляет программу.
//
// 2. struct — это тип-значение. Он хранится прямо "в теле" других объектов или в стеке,
//    без лишних аллокаций. То есть если у вас есть массив из 1000 Coordinate —
//    это просто кусок памяти подряд, без ссылок, без кучи. Быстро и эффективно.
//
// 3. Для математических типов важно, чтобы операции (сложение, вычитание и т.п.)
//    выполнялись максимально быстро, без создания новых ссылочных объектов.
//    Структуры идеально подходят для таких сценариев.
//
// 4. record больше подходит для "моделей данных" — то есть сущностей, которые описывают объекты предметной области,
//    например: Пользователь, Товар, Заказ. Они обычно живут дольше, часто передаются между слоями программы,
//    и их создание/удаление не так частое, как у числовых структур. Небольшие накладные расходы тут не страшны.
//
// 5. Иными словами:
//    - Если тип — это маленький набор чисел, координат, векторов, состояний, с которыми идут частые вычисления — struct.
//    - Если тип — это "описание чего-то в мире программы" (данные о человеке, заказе, сообщении и т.п.) — record.

// Когда использовать class, а когда record:
//
// 1. class — это основной ссылочный тип в C#.
//    Он подходит для объектов, которые:
//    - имеют изменяемое состояние (то есть свойства можно менять после создания);
//    - обладают поведением (методы, логика, внутренняя работа с состоянием);
//    - живут долго и часто изменяются во времени.
//
//    Примеры:
//    - Пользователь с балансом, который можно менять.
//    - Игровой объект, у которого меняются координаты.
//    - Подключение к базе данных, у которого есть методы открытия и закрытия.
//
//    Класс — это про "живущие объекты", которые ведут себя как сущности, а не как значения.
//
// 2. record — это тоже ссылочный тип (на самом деле класс под капотом),
//    но с другой философией: это *неизменяемые модели данных*.
//    Основные особенности record:
//    - значения полей задаются при создании и потом не меняются (через init или позиционный синтаксис);
//    - два record считаются равными, если совпадают все их поля (сравнение по значению, а не по ссылке);
//    - поддерживает удобный синтаксис копирования: `var newUser = oldUser with { Age = 25 };`.
//
//    record используют, когда объект описывает "данные как факт", а не "объект с поведением".
//    То есть он просто хранит информацию, но сам ничего не делает.
//
//    Примеры:
//    - Пользователь с фиксированными данными профиля;
//    - DTO (Data Transfer Object) для передачи между слоями приложения;
//    - Результаты вычислений или запросов, где важно значение, а не идентичность объекта.
//
// 3. Простыми словами:
//    - class — когда объект *живёт*, меняется и имеет поведение;
//    - record — когда объект *представляет данные*, которые не должны меняться и важны только по значению.
//
// 4. Если изобразить аналогию:
//    - class → "человек" (имеет жизнь, действия, меняет состояние);
//    - record → "паспортные данные человека" (фиксированные значения, просто информация);
//
// Итого:
// - Для вычислений и числовых структур → readonly struct.
// - Для неизменяемых моделей данных → record.
// - Для изменяемых и "живых" объектов → class.
